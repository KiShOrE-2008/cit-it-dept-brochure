// Helper calculations for summary statistics
export const computeAchievementStats = () => {
  const totalWinningTeams = achievementsData.length; // Each entry is ONE unique team achievement
  
  // Total Team Prize Money in INR
  const totalINR = achievementsData.reduce((sum, item) => sum + item.prizeINR, 0);
  
  // Total Team Prize Money in USD
  const totalUSD = achievementsData.reduce((sum, item) => sum + item.prizeUSD, 0);
  
  // Medals breakdown
  const goldCount = achievementsData.filter(i => i.badge.includes("1st") || i.badge.includes("GOLD") || i.badge.includes("Winner")).length;
  const silverCount = achievementsData.filter(i => i.badge.includes("2nd") || i.badge.includes("Silver") || i.badge.includes("Runner")).length;
  const bronzeCount = achievementsData.filter(i => i.badge.includes("3rd") || i.badge.includes("Bronze")).length;
  const totalMedals = goldCount + silverCount + bronzeCount;
  
  // Total unique students involved
  const allStudentsSet = new Set();
  achievementsData.forEach(item => item.students.forEach(s => allStudentsSet.add(s)));
  
  return {
    totalWinningTeams,
    totalINR,
    totalUSD,
    goldCount,
    silverCount,
    bronzeCount,
    totalMedals,
    uniqueStudentsCount: allStudentsSet.size
  };
};

